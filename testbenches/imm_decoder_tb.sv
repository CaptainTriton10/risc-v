`timescale 1ns/1ps

module tb_imm_decoder;

    // ── DUT ports ──────────────────────────────────────────────
    reg  [31:0] instr;
    reg  [6:0]  opcode;
    wire [31:0] imm32;

    // ── Instantiate DUT ────────────────────────────────────────
    imm_decoder uut (
        .instr  (instr),
        .opcode (opcode),
        .imm32  (imm32)
    );

    // ── Test tracking ──────────────────────────────────────────
    integer pass_count;
    integer fail_count;

    // ── Task: check one result ─────────────────────────────────
    task check;
        input [127:0] label;   // test name (up to 16 chars)
        input [31:0]  expected;
        begin
            #1; // let combinational settle
            if (imm32 === expected) begin
                $display("PASS  %0s  got=%08h", label, imm32);
                pass_count = pass_count + 1;
            end else begin
                $display("FAIL  %0s  expected=%08h  got=%08h",
                         label, expected, imm32);
                fail_count = fail_count + 1;
            end
        end
    endtask

    // ── Main test sequence ─────────────────────────────────────
    initial begin
        pass_count = 0;
        fail_count = 0;

        $display("=== imm_decoder testbench ===");

        // ──────────────────────────────────────────────────────
        // R-type (opcode 0110011) — no immediate, expect 0
        // ──────────────────────────────────────────────────────
        // ADD x1, x2, x3  →  funct7=0000000 rs2=00011 rs1=00010 funct3=000 rd=00001
        instr  = 32'b0000000_00011_00010_000_00001_0110011;
        opcode = 7'b0110011;
        check("R ADD       ", 32'h00000000);

        // SUB — different funct7, immediate should still be 0
        instr  = 32'b0100000_00011_00010_000_00001_0110011;
        opcode = 7'b0110011;
        check("R SUB       ", 32'h00000000);

        // ──────────────────────────────────────────────────────
        // I-type ALU (opcode 0010011)
        // ──────────────────────────────────────────────────────
        // ADDI x1, x2, 1   →  imm12 = 000000000001
        instr  = 32'b000000000001_00010_000_00001_0010011;
        opcode = 7'b0010011;
        check("I ADDI +1   ", 32'h00000001);

        // ADDI x1, x2, 2047  →  imm12 = 011111111111  (max positive 12-bit)
        instr  = 32'b011111111111_00010_000_00001_0010011;
        opcode = 7'b0010011;
        check("I ADDI +2047", 32'h000007FF);

        // ADDI x1, x2, -1   →  imm12 = 111111111111  (all ones = -1)
        instr  = 32'b111111111111_00010_000_00001_0010011;
        opcode = 7'b0010011;
        check("I ADDI -1   ", 32'hFFFFFFFF);

        // ADDI x1, x2, -2048  →  imm12 = 100000000000  (most negative 12-bit)
        instr  = 32'b100000000000_00010_000_00001_0010011;
        opcode = 7'b0010011;
        check("I ADDI -2048", 32'hFFFFF800);

        // ──────────────────────────────────────────────────────
        // I-type LOAD (opcode 0000011)
        // ──────────────────────────────────────────────────────
        // LW x1, 4(x2)   →  imm12 = 000000000100
        instr  = 32'b000000000100_00010_010_00001_0000011;
        opcode = 7'b0000011;
        check("I LW +4     ", 32'h00000004);

        // LW x1, -4(x2)  →  imm12 = 111111111100
        instr  = 32'b111111111100_00010_010_00001_0000011;
        opcode = 7'b0000011;
        check("I LW -4     ", 32'hFFFFFFFC);

        // ──────────────────────────────────────────────────────
        // I-type JALR (opcode 1100111)
        // ──────────────────────────────────────────────────────
        // JALR x0, x1, 0
        instr  = 32'b000000000000_00001_000_00000_1100111;
        opcode = 7'b1100111;
        check("I JALR 0    ", 32'h00000000);

        // JALR x0, x1, -4
        instr  = 32'b111111111100_00001_000_00000_1100111;
        opcode = 7'b1100111;
        check("I JALR -4   ", 32'hFFFFFFFC);

        // ──────────────────────────────────────────────────────
        // S-type (opcode 0100011)
        // imm[11:5] in instr[31:25], imm[4:0] in instr[11:7]
        // ──────────────────────────────────────────────────────
        // SW x2, 4(x1)   →  imm = 0000000_00100 → split: [11:5]=0000000, [4:0]=00100
        instr  = 32'b0000000_00010_00001_010_00100_0100011;
        opcode = 7'b0100011;
        check("S SW +4     ", 32'h00000004);

        // SW x2, -4(x1)  →  imm = 1111111_11100 → [11:5]=1111111, [4:0]=11100
        instr  = 32'b1111111_00010_00001_010_11100_0100011;
        opcode = 7'b0100011;
        check("S SW -4     ", 32'hFFFFFFFC);

        // SW x2, 2047(x1) → imm = 011111111111 → [11:5]=0111111, [4:0]=11111
        instr  = 32'b0111111_00010_00001_010_11111_0100011;
        opcode = 7'b0100011;
        check("S SW +2047  ", 32'h000007FF);

        // SW x2, -2048(x1) → imm = 100000000000 → [11:5]=1000000, [4:0]=00000
        instr  = 32'b1000000_00010_00001_010_00000_0100011;
        opcode = 7'b0100011;
        check("S SW -2048  ", 32'hFFFFF800);

        // ──────────────────────────────────────────────────────
        // B-type (opcode 1100011)
        // imm = {sign×19, [12], [11], [10:5], [4:1], 0}
        // instr: [31]=imm[12], [30:25]=imm[10:5], [11:8]=imm[4:1], [7]=imm[11]
        // ──────────────────────────────────────────────────────
        // BEQ, offset +4  →  imm = 0_0_000000_0010_0
        //   [31]=0 [30:25]=000000 [11:8]=0010 [7]=0
        instr  = 32'b0_000000_00000_00000_000_0010_0_1100011;
        opcode = 7'b1100011;
        check("B BEQ +4    ", 32'h00000004);

        // BEQ, offset +4096  →  imm[12]=1 (max positive, crosses 2^12)
        //   imm = 0_1_000000_0000_0  →  +4096 ... actually max pos is 4094
        //   Let's use offset +256: imm[8]=1, rest 0
        //   imm = 0_0_000001_0000_0  →  [30:25]=000001, all others 0
        instr  = 32'b0_000001_00000_00000_000_0000_0_1100011;
        opcode = 7'b1100011;
        check("B BEQ +64   ", 32'h00000040);

        // BEQ, offset -4  →  imm = 1_1_111111_1110_0
        //   [31]=1 [7]=1 [30:25]=111111 [11:8]=1110
        instr  = 32'b1_111111_00000_00000_000_1110_1_1100011;
        opcode = 7'b1100011;
        check("B BEQ -4    ", 32'hFFFFFFFC);

        // BEQ, offset -4096 (most negative B immediate)
        //   imm[12]=1, all other imm bits 0 → imm = 1_0_000000_0000_0
        //   [31]=1 [7]=0 [30:25]=000000 [11:8]=0000
        instr  = 32'b1_000000_00000_00000_000_0000_0_1100011;
        opcode = 7'b1100011;
        check("B BEQ -4096 ", 32'hFFFFF000);

        // ──────────────────────────────────────────────────────
        // U-type LUI (opcode 0110111)
        // imm = {instr[31:12], 12'b0}
        // ──────────────────────────────────────────────────────
        // LUI x1, 1   →  upper20 = 00000000000000000001
        instr  = 32'b00000000000000000001_00001_0110111;
        opcode = 7'b0110111;
        check("U LUI 1     ", 32'h00001000);

        // LUI x1, 0xABCDE
        instr  = 32'b10101011110011011110_00001_0110111;
        opcode = 7'b0110111;
        check("U LUI ABCDE ", 32'hABCDE000);

        // LUI x1, 0xFFFFF  (all ones in upper 20)
        instr  = 32'b11111111111111111111_00001_0110111;
        opcode = 7'b0110111;
        check("U LUI FFFFF ", 32'hFFFFF000);

        // ──────────────────────────────────────────────────────
        // U-type AUIPC (opcode 0010111) — same immediate encoding as LUI
        // ──────────────────────────────────────────────────────
        instr  = 32'b00000000000000000001_00001_0010111;
        opcode = 7'b0010111;
        check("U AUIPC 1   ", 32'h00001000);

        // ──────────────────────────────────────────────────────
        // J-type JAL (opcode 1101111)
        // imm = {sign×12, [19:12], [20], [30:21], 0}
        // instr: [31]=imm[20], [30:21]=imm[10:1], [20]=imm[11], [19:12]=imm[19:12]
        // ──────────────────────────────────────────────────────
        // JAL x1, +4   →  imm = 0_00000000_0_0000000010_0
        //   [31]=0 [19:12]=00000000 [20]=0 [30:21]=0000000010
        instr  = 32'b0_0000000010_0_00000000_00001_1101111;
        opcode = 7'b1101111;
        check("J JAL +4    ", 32'h00000004);

        // JAL x0, +256  →  imm[8]=1, rest 0
        //   [30:21]=0010000000 (imm[8] is bit 21+7=28? let's be precise)
        //   imm[10:1] lives in instr[30:21]; imm[8] = imm_bit8 → instr[29]
        //   imm=256: binary 0_00000000_0_0010000000_0 (imm[8]=1 → instr[29]=1)
        instr  = 32'b0_0010000000_0_00000000_00000_1101111;
        opcode = 7'b1101111;
        check("J JAL +256  ", 32'h00000100);

        // JAL x0, -4   →  imm = 1_11111111_1_1111111110_0
        //   [31]=1 [19:12]=11111111 [20]=1 [30:21]=1111111110
        instr  = 32'b1_1111111110_1_11111111_00000_1101111;
        opcode = 7'b1101111;
        check("J JAL -4    ", 32'hFFFFFFFC);

        // JAL x0, -1048576 (most negative J immediate, imm[20]=1 rest 0)
        //   [31]=1 [19:12]=00000000 [20]=0 [30:21]=0000000000
        instr  = 32'b1_0000000000_0_00000000_00000_1101111;
        opcode = 7'b1101111;
        check("J JAL -1M   ", 32'hFFF00000);

        // ──────────────────────────────────────────────────────
        // Default case — unknown opcode
        // ──────────────────────────────────────────────────────
        instr  = 32'hDEADBEEF;
        opcode = 7'b0000000;
        check("default     ", 32'h00000000);

        // ──────────────────────────────────────────────────────
        // Summary
        // ──────────────────────────────────────────────────────
        $display("─────────────────────────────────────");
        $display("Results: %0d passed, %0d failed", pass_count, fail_count);
        if (fail_count == 0)
            $display("All tests passed.");
        else
            $display("FAILURES DETECTED — check above.");
        $display("─────────────────────────────────────");
        $finish;
    end

endmodule